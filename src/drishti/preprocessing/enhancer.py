"""Adaptive 5-Stage Video Frame Enhancer for NETRA-4D Preprocessing Pipeline.

Applies targeted enhancements conditionally based on QualityReport defect flags:
1. Stage 1: Noise Reduction (Bilateral or Fast NL-Means)
2. Stage 2: CLAHE (Luminance Contrast Enhancement in LAB space)
3. Stage 3: Adaptive Gamma Correction (Power-law LUT)
4. Stage 4: Detail Restoration & Sharpening (Unsharp Masking with threshold)
5. Stage 5: Color Cast Neutralization (Gray World / Shades of Gray White Balance)
"""

from __future__ import annotations

from dataclasses import dataclass, field
import logging
import math
import time
from typing import Any, Dict, List, Optional, Tuple, Union
import cv2
import numpy as np

from drishti.preprocessing.config import (
    CLAHEConfig,
    DenoiseConfig,
    GammaConfig,
    PreprocessingConfig,
    SharpenConfig,
    WhiteBalanceConfig,
)
from drishti.preprocessing.quality import QualityFlag, QualityReport

logger = logging.getLogger(__name__)


@dataclass
class EnhancementResult:
    """Result of adaptive frame enhancement."""
    frame: np.ndarray
    stages_applied: List[str] = field(default_factory=list)
    stage_latencies_ms: Dict[str, float] = field(default_factory=dict)
    total_time_ms: float = 0.0


class AdaptiveFrameEnhancer:
    """Orchestrates the 5 adaptive image enhancement stages."""

    def __init__(self, config: Optional[PreprocessingConfig] = None):
        self.config = config or PreprocessingConfig()
        self._clahe_cache: Optional[cv2.CLAHE] = None
        self._setup_submodules()

    def _setup_submodules(self) -> None:
        """Initialize reusable OpenCV state objects."""
        if self.config.clahe.enabled:
            grid = self.config.clahe.tile_grid_size
            self._clahe_cache = cv2.createCLAHE(
                clipLimit=float(self.config.clahe.clip_limit),
                tileGridSize=(int(grid[0]), int(grid[1])),
            )

    def enhance(
        self,
        frame_bgr: np.ndarray,
        quality_report: Optional[QualityReport] = None,
        force_all_stages: bool = False,
    ) -> EnhancementResult:
        """Run adaptive enhancement pipeline on frame_bgr.
        
        Args:
            frame_bgr: BGR uint8 frame (H, W, 3).
            quality_report: QualityReport generated by FrameQualityAssessor.
            force_all_stages: If True, executes all enabled stages regardless of flags.

        Returns:
            EnhancementResult containing the enhanced frame and execution metrics.
        """
        start_total = time.perf_counter()

        if frame_bgr is None or frame_bgr.size == 0:
            return EnhancementResult(frame=frame_bgr, total_time_ms=0.0)

        # Check if preprocessing is disabled
        if not self.config.enabled or self.config.mode == "disabled":
            return EnhancementResult(frame=frame_bgr, total_time_ms=0.0)

        # Mode check: if 'always', force all enabled stages
        if self.config.mode == "always":
            force_all_stages = True

        current_frame = frame_bgr
        stages_applied: List[str] = []
        stage_latencies: Dict[str, float] = {}

        # -------------------------------------------------------------
        # STAGE 1: Noise Reduction
        # -------------------------------------------------------------
        should_denoise = self.config.denoise.enabled and (
            force_all_stages or (
                quality_report is not None and (
                    quality_report.is_noisy or
                    quality_report.noise_level > self.config.denoise.trigger_noise_threshold
                )
            )
        )
        if should_denoise:
            t0 = time.perf_counter()
            current_frame = self._apply_denoise(current_frame, self.config.denoise)
            t_ms = (time.perf_counter() - t0) * 1000.0
            stages_applied.append("denoise")
            stage_latencies["denoise"] = round(t_ms, 2)

        # -------------------------------------------------------------
        # STAGE 2: Contrast Enhancement (CLAHE)
        # -------------------------------------------------------------
        should_clahe = self.config.clahe.enabled and (
            force_all_stages or (
                quality_report is not None and (
                    quality_report.is_low_contrast or
                    quality_report.contrast < self.config.clahe.trigger_contrast_threshold
                )
            )
        )
        if should_clahe:
            t0 = time.perf_counter()
            current_frame = self._apply_clahe(current_frame, self.config.clahe)
            t_ms = (time.perf_counter() - t0) * 1000.0
            stages_applied.append("clahe")
            stage_latencies["clahe"] = round(t_ms, 2)

        # -------------------------------------------------------------
        # STAGE 3: Adaptive Gamma Correction
        # -------------------------------------------------------------
        should_gamma = self.config.gamma.enabled and (
            force_all_stages or (
                quality_report is not None and (
                    quality_report.is_dark or
                    quality_report.is_bright or
                    quality_report.brightness < self.config.gamma.low_brightness_threshold or
                    quality_report.brightness > self.config.gamma.high_brightness_threshold
                )
            )
        )
        if should_gamma:
            t0 = time.perf_counter()
            brightness_val = quality_report.brightness if quality_report else None
            current_frame = self._apply_gamma(current_frame, self.config.gamma, brightness_val)
            t_ms = (time.perf_counter() - t0) * 1000.0
            stages_applied.append("gamma")
            stage_latencies["gamma"] = round(t_ms, 2)

        # -------------------------------------------------------------
        # STAGE 4: Detail Restoration & Sharpening
        # -------------------------------------------------------------
        # Sharpen if blurry, but avoid sharpening when frame is noisy to prevent noise amplification
        should_sharpen = self.config.sharpen.enabled and (
            force_all_stages or (
                quality_report is not None and (
                    quality_report.is_blurry or
                    quality_report.blur_score < self.config.sharpen.trigger_blur_threshold
                ) and not quality_report.is_noisy
            )
        )
        if should_sharpen:
            t0 = time.perf_counter()
            current_frame = self._apply_sharpen(current_frame, self.config.sharpen)
            t_ms = (time.perf_counter() - t0) * 1000.0
            stages_applied.append("sharpen")
            stage_latencies["sharpen"] = round(t_ms, 2)

        # -------------------------------------------------------------
        # STAGE 5: Color Cast Neutralization (White Balance)
        # -------------------------------------------------------------
        should_wb = self.config.white_balance.enabled and (
            force_all_stages or (
                quality_report is not None and (
                    quality_report.has_color_cast or
                    quality_report.color_cast_score > self.config.white_balance.trigger_cast_threshold
                )
            )
        )
        if should_wb:
            t0 = time.perf_counter()
            current_frame = self._apply_white_balance(current_frame, self.config.white_balance)
            t_ms = (time.perf_counter() - t0) * 1000.0
            stages_applied.append("white_balance")
            stage_latencies["white_balance"] = round(t_ms, 2)

        total_ms = (time.perf_counter() - start_total) * 1000.0

        return EnhancementResult(
            frame=current_frame,
            stages_applied=stages_applied,
            stage_latencies_ms=stage_latencies,
            total_time_ms=round(total_ms, 2),
        )

    # =========================================================================
    # Internal Stage Implementations
    # =========================================================================

    def _apply_denoise(self, frame_bgr: np.ndarray, cfg: DenoiseConfig) -> np.ndarray:
        """Stage 1: Denoise frame preserving salient edges."""
        method = cfg.method.lower()
        if method == "bilateral":
            return cv2.bilateralFilter(
                frame_bgr,
                d=cfg.bilateral_d,
                sigmaColor=cfg.bilateral_sigma_color,
                sigmaSpace=cfg.bilateral_sigma_space,
            )
        elif method == "fast_nl_means":
            return cv2.fastNlMeansDenoisingColored(
                frame_bgr,
                None,
                h=cfg.nlmeans_h,
                hColor=cfg.nlmeans_h_color,
                templateWindowSize=cfg.nlmeans_template_window,
                searchWindowSize=cfg.nlmeans_search_window,
            )
        elif method == "gaussian":
            return cv2.GaussianBlur(frame_bgr, (5, 5), 0)
        else:
            # Fallback to bilateral
            return cv2.bilateralFilter(frame_bgr, d=7, sigmaColor=50.0, sigmaSpace=50.0)

    def _apply_clahe(self, frame_bgr: np.ndarray, cfg: CLAHEConfig) -> np.ndarray:
        """Stage 2: Contrast Limited Adaptive Histogram Equalization in LAB space."""
        if len(frame_bgr.shape) < 3 or frame_bgr.shape[2] != 3:
            # Grayscale fallback
            if self._clahe_cache is None:
                self._clahe_cache = cv2.createCLAHE(clipLimit=cfg.clip_limit, tileGridSize=cfg.tile_grid_size)
            return self._clahe_cache.apply(frame_bgr)

        lab = cv2.cvtColor(frame_bgr, cv2.COLOR_BGR2LAB)
        l, a, b = cv2.split(lab)

        if self._clahe_cache is None:
            self._clahe_cache = cv2.createCLAHE(clipLimit=cfg.clip_limit, tileGridSize=cfg.tile_grid_size)

        l_enhanced = self._clahe_cache.apply(l)
        lab_enhanced = cv2.merge([l_enhanced, a, b])
        return cv2.cvtColor(lab_enhanced, cv2.COLOR_LAB2BGR)

    def _apply_gamma(
        self,
        frame_bgr: np.ndarray,
        cfg: GammaConfig,
        current_brightness: Optional[float] = None,
    ) -> np.ndarray:
        """Stage 3: Adaptive power-law gamma correction via 256-element LUT."""
        if current_brightness is None:
            # Compute mean luminance quickly
            if len(frame_bgr.shape) == 3:
                # Approximate luminance Y = 0.299R + 0.587G + 0.114B
                mean_b = float(np.mean(frame_bgr[:, :, 0]))
                mean_g = float(np.mean(frame_bgr[:, :, 1]))
                mean_r = float(np.mean(frame_bgr[:, :, 2]))
                current_brightness = 0.114 * mean_b + 0.587 * mean_g + 0.299 * mean_r
            else:
                current_brightness = float(np.mean(frame_bgr))

        b_safe = max(5.0, min(250.0, current_brightness))
        target_b = cfg.target_brightness

        # Adaptive gamma calculation:
        # gamma = log(target / 255) / log(current / 255)
        try:
            gamma = math.log(target_b / 255.0) / math.log(b_safe / 255.0)
        except ZeroDivisionError:
            gamma = 1.0

        gamma = max(cfg.min_gamma, min(cfg.max_gamma, gamma))

        # If gamma is very close to 1.0, skip adjustment
        if abs(gamma - 1.0) < 0.05:
            return frame_bgr

        # Precompute LUT: I_out = 255 * (I_in / 255) ** gamma
        table = np.array([
            min(255, max(0, int(((i / 255.0) ** gamma) * 255.0 + 0.5)))
            for i in range(256)
        ], dtype=np.uint8)

        return cv2.LUT(frame_bgr, table)

    def _apply_sharpen(self, frame_bgr: np.ndarray, cfg: SharpenConfig) -> np.ndarray:
        """Stage 4: Unsharp masking with optional threshold."""
        radius = cfg.radius
        amount = cfg.amount
        threshold = cfg.threshold

        # Gaussian blur for base low-pass signal
        blurred = cv2.GaussianBlur(frame_bgr, (0, 0), sigmaX=radius, sigmaY=radius)

        if threshold <= 0:
            # Standard fast unsharp mask: frame * (1 + amount) - blurred * amount
            # addWeighted clips automatically
            return cv2.addWeighted(frame_bgr, 1.0 + amount, blurred, -amount, 0)

        # Unsharp mask with threshold to preserve smooth flat regions
        diff = cv2.absdiff(frame_bgr, blurred)
        # Where detail exceeds threshold, apply boost
        mask = (diff >= threshold).astype(np.float32)
        frame_f = frame_bgr.astype(np.float32)
        blurred_f = blurred.astype(np.float32)

        detail = (frame_f - blurred_f) * amount
        enhanced_f = frame_f + detail * mask
        return np.clip(enhanced_f, 0, 255).astype(np.uint8)

    def _apply_white_balance(self, frame_bgr: np.ndarray, cfg: WhiteBalanceConfig) -> np.ndarray:
        """Stage 5: Neutralize color cast via Gray World or Shades of Gray algorithm."""
        if len(frame_bgr.shape) < 3 or frame_bgr.shape[2] != 3:
            return frame_bgr

        method = cfg.method.lower()

        if method == "gray_world":
            # Gray world assumption: mean of each channel should equal gray mean
            mean_b = float(np.mean(frame_bgr[:, :, 0]))
            mean_g = float(np.mean(frame_bgr[:, :, 1]))
            mean_r = float(np.mean(frame_bgr[:, :, 2]))

            gray_mean = (mean_b + mean_g + mean_r) / 3.0

            kb = gray_mean / max(1.0, mean_b)
            kg = gray_mean / max(1.0, mean_g)
            kr = gray_mean / max(1.0, mean_r)

            # Limit gains to prevent excessive distortion
            kb = max(0.6, min(1.6, kb))
            kg = max(0.6, min(1.6, kg))
            kr = max(0.6, min(1.6, kr))

            lut_b = np.clip(np.arange(256) * kb, 0, 255).astype(np.uint8)
            lut_g = np.clip(np.arange(256) * kg, 0, 255).astype(np.uint8)
            lut_r = np.clip(np.arange(256) * kr, 0, 255).astype(np.uint8)

            b, g, r = cv2.split(frame_bgr)
            b_wb = cv2.LUT(b, lut_b)
            g_wb = cv2.LUT(g, lut_g)
            r_wb = cv2.LUT(r, lut_r)

            return cv2.merge([b_wb, g_wb, r_wb])

        elif method == "shades_of_gray":
            # Minkowski norm p
            p = float(cfg.p_norm)
            b, g, r = cv2.split(frame_bgr.astype(np.float32))

            norm_b = float(np.power(np.mean(np.power(b, p)), 1.0 / p))
            norm_g = float(np.power(np.mean(np.power(g, p)), 1.0 / p))
            norm_r = float(np.power(np.mean(np.power(r, p)), 1.0 / p))

            gray_norm = (norm_b + norm_g + norm_r) / 3.0

            kb = max(0.6, min(1.6, gray_norm / max(1.0, norm_b)))
            kg = max(0.6, min(1.6, gray_norm / max(1.0, norm_g)))
            kr = max(0.6, min(1.6, gray_norm / max(1.0, norm_r)))

            lut_b = np.clip(np.arange(256) * kb, 0, 255).astype(np.uint8)
            lut_g = np.clip(np.arange(256) * kg, 0, 255).astype(np.uint8)
            lut_r = np.clip(np.arange(256) * kr, 0, 255).astype(np.uint8)

            b_orig, g_orig, r_orig = cv2.split(frame_bgr)
            return cv2.merge([
                cv2.LUT(b_orig, lut_b),
                cv2.LUT(g_orig, lut_g),
                cv2.LUT(r_orig, lut_r),
            ])

        else:
            # Fallback
            return frame_bgr
