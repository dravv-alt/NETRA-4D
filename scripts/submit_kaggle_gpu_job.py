"""Bundle and submit the real full-video pipeline to a Kaggle GPU kernel.

This script deliberately never opens or copies ``kaggle.json``. It sets
``KAGGLE_CONFIG_DIR`` to the key's parent directory and lets the official
Kaggle CLI authenticate. Only an explicit whitelist of source/model files is
placed in the submission bundle, so credentials cannot enter the kernel.
"""

from __future__ import annotations

import argparse
import base64
import io
import json
import os
from pathlib import Path
import shutil
import subprocess
import sys
import zipfile


ROOT = Path(__file__).resolve().parent.parent
DEFAULT_KEY = ROOT / "kaggle.json"
DEFAULT_BUNDLE = ROOT / "outputs" / "kaggle_submission_bundle"


ENTRYPOINT_TEMPLATE = r'''"""Kaggle GPU entrypoint generated by NETRA-4D."""
import base64
import io
import os
from pathlib import Path
import shutil
import subprocess
import sys
import zipfile

ROOT = Path("/kaggle/working/netra4d_source")
ROOT.mkdir(parents=True, exist_ok=True)
with zipfile.ZipFile(io.BytesIO(base64.b64decode({source_archive_b64!r}))) as archive:
    archive.extractall(ROOT)
os.chdir(ROOT)
subprocess.run([
    sys.executable, "-m", "pip", "install", "-q",
    "ultralytics>=8.4.0", "opencv-python-headless>=4.8.0",
    "pydantic>=2.0.0", "requests>=2.31.0",
], check=True)
subprocess.run([
    sys.executable, "-m", "pip", "install", "-q", "--force-reinstall",
    "torch==2.7.1", "torchvision==0.22.1",
    "--index-url", "https://download.pytorch.org/whl/cu118",
], check=True)
import torch
if not torch.cuda.is_available():
    raise RuntimeError("CUDA was required but is not available in this Kaggle runtime.")
from ultralytics import YOLO
models = ROOT / "models" / "weights"
models.mkdir(parents=True, exist_ok=True)
for model_name in ("yolo26n-pose.pt", "yolo26n.pt"):
    model = YOLO(model_name)  # downloads the official Ultralytics weight if absent
    downloaded = Path(getattr(model, "ckpt_path", model_name))
    if not downloaded.is_file():
        downloaded = Path(model_name)
    if not downloaded.is_file():
        raise RuntimeError(f"Ultralytics did not materialize required model: {{model_name}}")
    shutil.copy2(downloaded, models / model_name)
subprocess.run([
    sys.executable, str(ROOT / "scripts" / "render_annotated_videos.py"),
    "--device", "cuda:0", "--require-cuda",
    "--phone-confidence", "0.70",
    "--output-dir", "/kaggle/working/netra4d_outputs",
    "--pose-model", "models/weights/yolo26n-pose.pt",
    "--object-model", "models/weights/yolo26n.pt",
    "--run-id", {run_id!r},
    "--progress-every", "250",
{asset_arguments}
], cwd=ROOT, check=True)
'''
# Backward-compatible inspection template. The submitted file is rendered from
# ENTRYPOINT_TEMPLATE with a concrete run ID and optional asset list.
ENTRYPOINT = ENTRYPOINT_TEMPLATE


def checked_copy(source: Path, destination: Path) -> None:
    if not source.exists():
        raise FileNotFoundError(f"Required submission file is missing: {source}")
    destination.parent.mkdir(parents=True, exist_ok=True)
    shutil.copy2(source, destination)


def source_archive_b64() -> str:
    """Return only executable source/configuration needed by the kernel.

    Kaggle script kernels execute the submitted code file but do not guarantee
    that sibling files are mounted at the code file's directory. Embedding this
    small source archive makes the runtime layout deterministic. Model weights
    are deliberately excluded and downloaded by the official model loader.
    """
    members = [
        ROOT / "scripts" / "render_annotated_videos.py",
        ROOT / "scripts" / "run_verified_inference.py",
        ROOT / "drishti4d" / "configs" / "datasets.json",
        *sorted((ROOT / "drishti4d" / "configs" / "workstations").glob("VIDEO_*.yaml")),
        *sorted((ROOT / "src").rglob("*.py")),
    ]
    buffer = io.BytesIO()
    with zipfile.ZipFile(buffer, "w", compression=zipfile.ZIP_DEFLATED) as archive:
        for member in members:
            if not member.is_file():
                raise FileNotFoundError(f"Required submission file is missing: {member}")
            archive.write(member, member.relative_to(ROOT).as_posix())
    return base64.b64encode(buffer.getvalue()).decode("ascii")


def build_bundle(
    bundle: Path, username: str, slug: str, *, run_id: str, assets: list[str], title: str | None = None,
) -> Path:
    if bundle.exists():
        shutil.rmtree(bundle)
    bundle.mkdir(parents=True)
    for relative in [
        "scripts/render_annotated_videos.py",
        "scripts/run_verified_inference.py",
        "drishti4d/configs/datasets.json",
    ]:
        checked_copy(ROOT / relative, bundle / relative)
    shutil.copytree(ROOT / "src", bundle / "src")
    asset_arguments = "\n".join(f'    "--asset", {asset!r},' for asset in assets)
    entrypoint = ENTRYPOINT_TEMPLATE.format(
        run_id=run_id, asset_arguments=asset_arguments,
        source_archive_b64=source_archive_b64(),
    )
    (bundle / "kaggle_entrypoint.py").write_text(entrypoint, encoding="utf-8")
    metadata = {
        "id": f"{username}/{slug}",
        "title": title or "NETRA 4D Full Video Real Model Inference",
        "code_file": "kaggle_entrypoint.py",
        "language": "python",
        "kernel_type": "script",
        "is_private": True,
        "enable_gpu": True,
        "enable_internet": True,
        "dataset_sources": [],
        "competition_sources": [],
        "kernel_sources": [],
    }
    (bundle / "kernel-metadata.json").write_text(
        json.dumps(metadata, indent=2), encoding="utf-8"
    )
    return bundle


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--username", required=True, help="Kaggle account username")
    parser.add_argument("--slug", default="netra-4d-full-video-real-model-inference")
    parser.add_argument("--title", help="Kaggle notebook title; set it to match an existing notebook slug")
    parser.add_argument("--key", type=Path, default=DEFAULT_KEY)
    parser.add_argument("--bundle", type=Path, default=DEFAULT_BUNDLE)
    parser.add_argument("--run-id", default="kaggle_gpu_full_video")
    parser.add_argument("--asset", action="append", default=[])
    parser.add_argument("--build-only", action="store_true")
    return parser.parse_args()


def main() -> int:
    args = parse_args()
    key = args.key.resolve()
    if key.name.lower() != "kaggle.json":
        raise ValueError("--key must point to a file named kaggle.json")
    if not key.is_file():
        raise FileNotFoundError(f"Kaggle key not found: {key}")
    # Do not open key. Only the official client receives its containing folder.
    bundle = build_bundle(
        args.bundle.resolve(), args.username, args.slug,
        run_id=args.run_id, assets=args.asset, title=args.title,
    )
    print(f"Credential-safe bundle created: {bundle}")
    if args.build_only:
        return 0
    environment = os.environ.copy()
    environment["KAGGLE_CONFIG_DIR"] = str(key.parent)
    kaggle_executable = shutil.which("kaggle")
    command = (
        [kaggle_executable, "kernels", "push", "-p", str(bundle)]
        if kaggle_executable
        else [sys.executable, "-m", "kaggle", "kernels", "push", "-p", str(bundle)]
    )
    subprocess.run(command, env=environment, check=True)
    print(f"Submitted: https://www.kaggle.com/code/{args.username}/{args.slug}")
    print("Download completed outputs with:")
    print(
        f"  python -m kaggle kernels output {args.username}/{args.slug} "
        "-p outputs/kaggle_results --force"
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
